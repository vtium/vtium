//! Generates vtium-term's X11 color name table from X.Org's rgb.txt.
//! README.md says what it writes and how to run it.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

/// The X.Org rgb release whose rgb.txt the table carries.
const RELEASE: &str = "rgb-1.1.1";

/// The SHA-256 of rgb.txt in [`RELEASE`].
const PIN: &str = "f8e3a7bea17acc0b91e6285c5d32001db27d84c4461c655afdbce9dbeb4fb6f0";

/// The licence of rgb.txt, the release's COPYING, copied into the table.
const LICENSE: &str = include_str!("rgb-license.txt");

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let [rgb_txt] = args.as_slice() else {
        eprintln!("usage: gen-color-names RGB_TXT");
        return ExitCode::from(2);
    };
    match run(Path::new(rgb_txt)) {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("gen-color-names: {e}");
            ExitCode::FAILURE
        }
    }
}

fn run(rgb_txt: &Path) -> Result<(), String> {
    let out = Path::new(env!("CARGO_MANIFEST_DIR")).join("../src/terminal/color");
    let bytes = std::fs::read(rgb_txt).map_err(|e| {
        format!(
            "{}: {e}; fetch https://www.x.org/releases/individual/app/{RELEASE}.tar.xz",
            rgb_txt.display()
        )
    })?;
    let got = hex(&sha256(&bytes));
    if got != PIN {
        return Err(format!("rgb.txt: sha256 {got}, pinned {PIN}"));
    }
    let text = String::from_utf8(bytes).map_err(|e| format!("rgb.txt: {e}"))?;

    let names = table(&text)?;
    write(&out.join("names.rs"), &names_rs(&names)?)?;
    write(&out.join("rgb.txt"), &text)?;
    let bytes: usize = names.keys().map(|n| n.len() + 6).sum();
    println!(
        "src/terminal/color/names.rs: {RELEASE}, {} names, {bytes} bytes",
        names.len()
    );
    Ok(())
}

fn write(path: &PathBuf, text: &str) -> Result<(), String> {
    std::fs::write(path, text).map_err(|e| format!("{}: {e}", path.display()))
}

/// Each name rgb.txt lists, lowercased with its spaces removed, and its
/// color. A line it cannot read, and a name two lines give two colors,
/// are errors.
fn table(text: &str) -> Result<BTreeMap<String, [u8; 3]>, String> {
    let mut names = BTreeMap::new();
    for (n, line) in text.lines().enumerate() {
        let err = |what: &str| format!("rgb.txt:{}: {what}: {line:?}", n + 1);
        if line.trim().is_empty() || line.starts_with('!') {
            continue;
        }
        let mut fields = line.split_whitespace();
        let mut channel = || -> Result<u8, String> {
            let field = fields.next().ok_or_else(|| err("too few fields"))?;
            field.parse().map_err(|_| err("not a channel"))
        };
        let rgb = [channel()?, channel()?, channel()?];
        let name: String = fields.collect::<String>().to_ascii_lowercase();
        if name.is_empty() || !name.bytes().all(|b| b.is_ascii_alphanumeric()) {
            return Err(err("not a name"));
        }
        if let Some(other) = names.insert(name, rgb)
            && other != rgb
        {
            return Err(err("a name given two colors"));
        }
    }
    Ok(names)
}

/// `text` as `//` comment lines.
fn commented(text: &str) -> String {
    let mut out = String::new();
    for line in text.lines() {
        out.push_str("//");
        if !line.is_empty() {
            out.push(' ');
            out.push_str(line);
        }
        out.push('\n');
    }
    out
}

fn names_rs(names: &BTreeMap<String, [u8; 3]>) -> Result<String, String> {
    let mut out = format!(
        "// Generated by crates/vtium-term/gen-color-names from rgb.txt of X.Org's\n\
         // {RELEASE}, the file beside this one. Do not edit; rerun the generator.\n\
         //\n\
         // rgb.txt is under this licence:\n\
         //\n"
    );
    out += &commented(LICENSE);
    let longest = names.keys().map(String::len).max().unwrap_or(0);
    let _ = write!(
        out,
        "\n/// The longest name in [`TEXT`].\n\
         pub(super) const NAME_MAX: usize = {longest};\n\
         \n\
         /// rgb.txt's names, each lowercased with its spaces removed, sorted and\n\
         /// run together.\n\
         pub(super) static TEXT: &str = \"\\\n"
    );
    let mut entries = String::new();
    let mut start = 0usize;
    for (i, (name, [r, g, b])) in names.iter().enumerate() {
        out += name;
        out += if i + 1 == names.len() {
            "\";\n"
        } else {
            "\\\n"
        };
        let at = u16::try_from(start).map_err(|_| "TEXT is past 64 KiB")?;
        let len = u8::try_from(name.len()).map_err(|_| format!("{name}: too long"))?;
        let _ = writeln!(entries, "    ({at}, {len}, [{r}, {g}, {b}]),");
        start += name.len();
    }
    let _ = write!(
        out,
        "\n/// Each name's start in [`TEXT`], its length and its color, in\n\
         /// [`TEXT`]'s order.\n\
         pub(super) static NAMES: [(u16, u8, [u8; 3]); {}] = [\n{entries}];\n",
        names.len()
    );
    Ok(out)
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().fold(String::new(), |mut s, b| {
        let _ = write!(s, "{b:02x}");
        s
    })
}
/// SHA-256, FIPS 180-4.
fn sha256(data: &[u8]) -> [u8; 32] {
    const K: [u32; 64] = [
        0x428a2f98, 0x71374491, 0xb5c0fbcf, 0xe9b5dba5, 0x3956c25b, 0x59f111f1, 0x923f82a4,
        0xab1c5ed5, 0xd807aa98, 0x12835b01, 0x243185be, 0x550c7dc3, 0x72be5d74, 0x80deb1fe,
        0x9bdc06a7, 0xc19bf174, 0xe49b69c1, 0xefbe4786, 0x0fc19dc6, 0x240ca1cc, 0x2de92c6f,
        0x4a7484aa, 0x5cb0a9dc, 0x76f988da, 0x983e5152, 0xa831c66d, 0xb00327c8, 0xbf597fc7,
        0xc6e00bf3, 0xd5a79147, 0x06ca6351, 0x14292967, 0x27b70a85, 0x2e1b2138, 0x4d2c6dfc,
        0x53380d13, 0x650a7354, 0x766a0abb, 0x81c2c92e, 0x92722c85, 0xa2bfe8a1, 0xa81a664b,
        0xc24b8b70, 0xc76c51a3, 0xd192e819, 0xd6990624, 0xf40e3585, 0x106aa070, 0x19a4c116,
        0x1e376c08, 0x2748774c, 0x34b0bcb5, 0x391c0cb3, 0x4ed8aa4a, 0x5b9cca4f, 0x682e6ff3,
        0x748f82ee, 0x78a5636f, 0x84c87814, 0x8cc70208, 0x90befffa, 0xa4506ceb, 0xbef9a3f7,
        0xc67178f2,
    ];
    let mut h: [u32; 8] = [
        0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a, 0x510e527f, 0x9b05688c, 0x1f83d9ab,
        0x5be0cd19,
    ];

    // the message, a 1 bit, zeros to 56 bytes mod 64, and its length in bits
    let mut msg = data.to_vec();
    msg.push(0x80);
    while msg.len() % 64 != 56 {
        msg.push(0);
    }
    msg.extend_from_slice(&((data.len() as u64) * 8).to_be_bytes());

    for block in msg.as_chunks::<64>().0 {
        let mut w = [0u32; 64];
        for (wi, word) in w.iter_mut().zip(block.as_chunks::<4>().0) {
            *wi = u32::from_be_bytes(*word);
        }
        for i in 16..64 {
            let s0 = w[i - 15].rotate_right(7) ^ w[i - 15].rotate_right(18) ^ (w[i - 15] >> 3);
            let s1 = w[i - 2].rotate_right(17) ^ w[i - 2].rotate_right(19) ^ (w[i - 2] >> 10);
            w[i] = w[i - 16]
                .wrapping_add(s0)
                .wrapping_add(w[i - 7])
                .wrapping_add(s1);
        }
        let [mut a, mut b, mut c, mut d, mut e, mut f, mut g, mut hh] = h;
        for (k, wi) in K.iter().zip(w) {
            let s1 = e.rotate_right(6) ^ e.rotate_right(11) ^ e.rotate_right(25);
            let ch = (e & f) ^ (!e & g);
            let t1 = hh
                .wrapping_add(s1)
                .wrapping_add(ch)
                .wrapping_add(*k)
                .wrapping_add(wi);
            let s0 = a.rotate_right(2) ^ a.rotate_right(13) ^ a.rotate_right(22);
            let maj = (a & b) ^ (a & c) ^ (b & c);
            let t2 = s0.wrapping_add(maj);
            hh = g;
            g = f;
            f = e;
            e = d.wrapping_add(t1);
            d = c;
            c = b;
            b = a;
            a = t1.wrapping_add(t2);
        }
        for (hi, x) in h.iter_mut().zip([a, b, c, d, e, f, g, hh]) {
            *hi = hi.wrapping_add(x);
        }
    }

    let mut out = [0u8; 32];
    for (chunk, hi) in out.as_chunks_mut::<4>().0.iter_mut().zip(h) {
        *chunk = hi.to_be_bytes();
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names_fold_case_and_spaces_and_keep_one_color() {
        let names = table("! a comment\n255 250 250\t\tsnow\n 47  79  79\t\tdark slate gray\n 47  79  79\t\tDarkSlateGray\n").unwrap();
        assert_eq!(
            names.into_iter().collect::<Vec<_>>(),
            [
                ("darkslategray".to_string(), [47, 79, 79]),
                ("snow".to_string(), [255, 250, 250]),
            ]
        );
        assert!(table("1 2 3\tred\n1 2 4\tRed\n").is_err());
        assert!(table("1 2\n").is_err());
        assert!(table("1 2 256\tred\n").is_err());
        assert!(table("1 2 3\tred-ish\n").is_err());
    }

    #[test]
    fn sha256_matches_fips_180_examples() {
        assert_eq!(
            hex(&sha256(b"abc")),
            "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"
        );
        assert_eq!(
            hex(&sha256(b"")),
            "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"
        );
        assert_eq!(
            hex(&sha256(
                b"abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq"
            )),
            "248d6a61d20638b8e5c026930c3e6039a33ce45964ff2167f6ecedd419db06c1"
        );
    }
}
