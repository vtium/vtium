//! The tables that blend a partly transparent picture pixel in linear
//! light, and the blend itself.
//!
//! A picture's pixels are stored in sRGB, the encoding displays use, where
//! equal steps of a byte look like equal steps of brightness. Light adds
//! up in linear terms, so a partly transparent pixel mixes with the pixel
//! below it correctly only after both are turned into linear light. vtium
//! does that with three tables and whole numbers alone, so that every
//! machine, and the GPU path's shader, draws the same bytes:
//!
//! - [`RECIPROCAL`] turns a premultiplied channel back into its straight
//!   color: `255 * 65536 / alpha`, rounded, so that a multiply and a shift
//!   take the place of a division.
//! - [`TO_LINEAR`] turns an sRGB byte into linear light as a 16-bit value,
//!   0 for black and 65,520 for full brightness, which is 16 times the
//!   4,095 steps of [`TO_SRGB`].
//! - [`TO_SRGB`] turns linear light, cut to 4,096 steps, back into an sRGB
//!   byte.
//!
//! The image store keeps each picture as premultiplied sRGB, and the blend
//! converts as it draws. Turning a premultiplied byte back into a straight
//! color loses precision at a low alpha, so a pixel with an alpha below 16
//! can land up to 10 levels from an exact blend in floating point, one
//! with an alpha of 16 or more up to 3, and one of 64 or more up to 2.
//!
//! References:
//! - ADR-1300 D7: pictures blend in linear light, through these three
//!   tables, from the store's premultiplied sRGB.
//! - ADR-1100 D2: the store's one format, premultiplied sRGB at 4 bytes a
//!   pixel.

/// `255 * 65536 / a`, rounded, for each alpha `a` from 1 to 255; 0 for an
/// alpha of 0, which the blend never divides by.
///
/// A premultiplied channel `s` times the entry for its alpha, shifted
/// right by 16 bits, is `s * 255 / a`: the channel's straight color.
#[cfg(feature = "images")]
pub(crate) static RECIPROCAL: [u32; 256] = reciprocals();

#[cfg(feature = "images")]
const fn reciprocals() -> [u32; 256] {
    let mut t = [0u32; 256];
    let mut a = 1u32;
    while a < 256 {
        // a is at least 1, and 255 * 65536 + a / 2 is far below 2^32
        #[expect(
            clippy::arithmetic_side_effects,
            clippy::indexing_slicing,
            reason = "a const loop over 1..=255"
        )]
        {
            t[a as usize] = (255 * 65536 + a / 2) / a;
            a += 1;
        }
    }
    t
}

