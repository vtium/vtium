/// The script of `locale`'s language, as locale(7) names a locale,
/// `language[_territory][.codeset][@modifier]`, by its Scripts.txt name:
/// Latin where the modifier is `latin`, as in `sr_RS@latin`. `None` for
/// the C and POSIX locales and a language the table lacks.
pub fn script_of(locale: &str) -> Option<&'static str> {
    if locale
        .rsplit_once('@')
        .is_some_and(|(_, m)| m.eq_ignore_ascii_case("latin"))
    {
        return Some("Latin");
    }
    let language = language(locale);
    LANGUAGES
        .iter()
        .find(|(code, _)| *code == language)
        .map(|&(_, script)| script)
}

/// The main exemplar characters of `locale`'s language in CLDR, the
/// letters its everyday text uses, in order: the lower-case letters, and
/// the marks and signs written with them. None for the C and POSIX
/// locales and a language the table lacks. Norwegian Bokmål (`nb`) takes
/// Norwegian's (`no`), the CLDR locale that holds them.
pub fn of_locale(locale: &str) -> Vec<char> {
    script_of(locale).map_or_else(Vec::new, |_| {
        let language = language(locale);
        let language = match language.as_str() {
            "nb" => "no",
            other => other,
        };
        data::EXEMPLARS
            .iter()
            .find(|(name, _)| *name == language)
            .map(|(_, ranges)| {
                ranges
                    .iter()
                    .flat_map(|&(a, b)| (a..=b).filter_map(char::from_u32))
                    .collect()
            })
            .unwrap_or_default()
    })
}

/// `locale`'s language, lower case: what comes before its `_`, `.` or `@`.
fn language(locale: &str) -> String {
    locale
        .split(['_', '.', '@'])
        .next()
        .unwrap_or_default()
        .to_ascii_lowercase()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_locales_language_names_its_script() {
        assert_eq!(script_of("hi_IN.UTF-8"), Some("Devanagari"));
        assert_eq!(script_of("en_US.UTF-8"), Some("Latin"));
        assert_eq!(script_of("sr_RS.UTF-8"), Some("Cyrillic"));
        assert_eq!(script_of("sr_RS@latin"), Some("Latin"));
        assert_eq!(script_of("ZH_CN"), Some("Han"));
        assert_eq!(script_of("C.UTF-8"), None);
        assert_eq!(script_of("POSIX"), None);
        assert_eq!(script_of(""), None);
    }

    // ADR-1401 D7: the letters are CLDR's main exemplar characters for the
    // locale's language
    #[test]
    fn a_locales_letters_are_its_languages_everyday_letters() {
        let az: Vec<char> = ('a'..='z').collect();
        assert_eq!(of_locale("en_US.UTF-8"), az);
        let de = of_locale("de_DE.UTF-8");
        assert_eq!(de.len(), 30);
        assert!(['ä', 'ö', 'ü', 'ß'].iter().all(|c| de.contains(c)));
        let hi = of_locale("hi_IN");
        assert!(hi.contains(&'\u{915}') && hi.contains(&'\u{93e}'));
        assert!(!hi.contains(&'a') && !hi.contains(&'\u{966}'), "no digits");
        assert!(of_locale("nb_NO.UTF-8").contains(&'å'));
        assert!(of_locale("C").is_empty() && of_locale("POSIX").is_empty());
        for &(language, _) in LANGUAGES {
            assert!(!of_locale(language).is_empty(), "{language}");
        }
    }
}
