//! The letters a locale's language uses every day, and the script they
//! are written in (ADR-1401 D7, ADR-1302 D14).
//!
//! `vtium check-config` warns when a font set leaves the letters of the
//! system locale's language to the last step of the fallback, the
//! squeeze. This module gives it those letters and the script's name. The
//! letters are the language's main exemplar characters in Unicode's
//! Common Locale Data Repository (CLDR), such as a to z for English, with
//! ä, ö, ü and ß for German, and the Devanagari letters and signs for
//! Hindi. `data.rs` holds them as ranges, generated by vtium-config's
//! `gen-shaping` with CLDR's licence notice. A small table here maps each
//! language to the script it is written in, which the warning names.

mod data;

