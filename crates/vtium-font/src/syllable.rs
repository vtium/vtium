//! Syllables that Unicode's grapheme cluster rules cut into several
//! clusters (ADR-1203).
//!
//! In Kannada, Tamil, Sinhala, Brahmi, Newa and many other scripts, a
//! conjunct of two consonants is two grapheme clusters by UAX #29: ಕ್ರ
//! (ka, virama, ra) is ಕ್ in one cluster and ರ in the next. The terminal
//! keeps those clusters and their cells. The console asks the glyph
//! helper for the whole syllable, and the helper shapes it once and draws
//! it across the cells of all its clusters, so the conjunct forms as the
//! font designs it.
//!
//! [`joins`] is the rule of ADR-1203 D1 for two clusters side by side: the
//! first ends with a linker, a character whose Indic_Syllabic_Category is
//! Virama, Invisible_Stacker or Consonant_With_Stacker, optionally followed
//! by U+200D ZERO WIDTH JOINER, and holds a consonant before the linker, as
//! rule GB9c of UAX #29 asks; the second starts with a Consonant, or,
//! after an Invisible_Stacker, with a Vowel_Independent; and the two
//! characters share a value of Script_Extensions. It is the rule by which
//! UAX #44 derives the Indic_Conjunct_Break values that rule GB9c of UAX
//! #29 joins by, without UAX #44's list of scripts. `data.rs` holds the
//! characters, generated by vtium-config's `gen-shaping` from the Unicode
//! Character Database.
//!
//! Each cluster of a syllable draws its own part of the syllable's glyph,
//! its [`Piece`], in its own cells. A piece's key ([`Piece::key`]) is the
//! syllable's text, then U+001F INFORMATION SEPARATOR ONE, then the
//! piece's mark ([`Piece::mark`]), a character of Supplementary Private
//! Use Area-B that says where the cluster's cells lie among the
//! syllable's. Only the console's syllable finder makes a key, for the
//! cells it finds in a syllable. A program can write a mark, and rule GB9b
//! of UAX #29 keeps one in a cluster after a Prepend character such as
//! U+0600. But U+001F is a control character: rules GB4 and GB5 break a
//! cluster on both sides of it, so no cluster of two characters or more
//! holds it. So no cell's own cluster is a piece's key, and a cluster that
//! ends with a mark draws as ordinary text.

mod data;

use crate::bounds::CLUSTER_SCALARS_MAX;

/// The version of the Unicode Character Database the tables come from.
pub const UNICODE_VERSION: &str = data::VERSION;

/// The most scalar values a syllable's text holds: one key's worth, less
/// the separator and the piece's mark that follow the text in each piece's
/// key. A run of joined clusters whose text is longer draws split
/// (ADR-1203 D1).
pub const SYLLABLE_SCALARS_MAX: usize = CLUSTER_SCALARS_MAX as usize - 2;

/// U+001F INFORMATION SEPARATOR ONE, which stands between a piece key's
/// text and its mark. UAX #29 never puts a control character in a cluster
/// with another character, so no cell's cluster holds it.
const SEPARATOR: char = '\u{1f}';

/// The most cells a syllable takes: two for each of its scalar values.
#[expect(
    clippy::cast_possible_truncation,
    reason = "28 cells, which the test of the marks holds the bound to"
)]
const TOTAL_MAX: u8 = 2 * SYLLABLE_SCALARS_MAX as u8;

/// ZERO WIDTH JOINER, which may follow a linker.
const ZWJ: char = '\u{200d}';

/// The first character of Supplementary Private Use Area-B, the mark of
/// the piece at the start of a syllable of no cells.
const MARK_BASE: u32 = 0x10_0000;

/// A character's Indic_Syllabic_Category, among those ADR-1203 D1 reads.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Category {
    Virama,
    InvisibleStacker,
    ConsonantWithStacker,
    Consonant,
    VowelIndependent,
}

/// `c`'s category and the index of its scripts in [`data::SETS`], when
/// `c` is a linker or a follower.
fn syllabic(c: char) -> Option<(Category, u16)> {
    let c = u32::from(c);
    let i = data::SYLLABIC.partition_point(|&(_, last, _, _)| last < c);
    let &(first, _, category, set) = data::SYLLABIC.get(i)?;
    if first > c {
        return None;
    }
    let category = match category {
        1 => Category::Virama,
        2 => Category::InvisibleStacker,
        3 => Category::ConsonantWithStacker,
        4 => Category::Consonant,
        5 => Category::VowelIndependent,
        _ => return None,
    };
    Some((category, set))
}

/// Whether two sets of [`data::SETS`] share a script.
fn share(a: u16, b: u16) -> bool {
    let set = |i: u16| data::SETS.get(usize::from(i)).copied().unwrap_or(&[]);
    let (a, b) = (set(a), set(b));
    a.iter().any(|s| b.contains(s))
}

/// Whether the cluster `left` joins the cluster `right`, written after it
/// on the same row, into one syllable (ADR-1203 D1). `left` ends with a
/// linker, optionally followed by U+200D, and a consonant comes before the
/// linker in `left`, as rule GB9c of UAX #29 asks; a consonant with its
/// own stacker is that consonant itself. `right` starts with a consonant,
/// or with an independent vowel after an invisible stacker. The linker and
/// the character after it share a script. A cluster that ends with U+200C
/// ZERO WIDTH NON-JOINER keeps its virama and joins nothing.
pub fn joins(left: &[char], right: &[char]) -> bool {
    let left = match left {
        [rest @ .., ZWJ] => rest,
        _ => left,
    };
    let (Some(&linker), Some(&follower)) = (left.last(), right.first()) else {
        return false;
    };
    // a quick answer for the text of most rows: no linker or follower
    // lies before the Devanagari block
    if u32::from(follower) < 0x900 {
        return false;
    }
    let Some((link, a)) = syllabic(linker) else {
        return false;
    };
    let Some((follow, b)) = syllabic(follower) else {
        return false;
    };
    let follows = match link {
        Category::Virama | Category::ConsonantWithStacker => follow == Category::Consonant,
        Category::InvisibleStacker => {
            matches!(follow, Category::Consonant | Category::VowelIndependent)
        }
        Category::Consonant | Category::VowelIndependent => false,
    };
    // as rule GB9c of UAX #29 asks, a consonant comes before the linker:
    // the cluster holds one, or the linker is a consonant with its own
    // stacker
    let body = left.split_last().map_or(&[][..], |(_, body)| body);
    let consonant = link == Category::ConsonantWithStacker
        || body
            .iter()
            .any(|&c| syllabic(c).is_some_and(|(cat, _)| cat == Category::Consonant));
    follows && consonant && share(a, b)
}

/// Whether `c` is a linker: a character whose Indic_Syllabic_Category is
/// Virama, Invisible_Stacker or Consonant_With_Stacker, which joins the
/// consonant after it into a conjunct.
pub fn is_linker(c: char) -> bool {
    syllabic(c).is_some_and(|(cat, _)| {
        matches!(
            cat,
            Category::Virama | Category::InvisibleStacker | Category::ConsonantWithStacker
        )
    })
}

/// Whether `c` may end a cluster that joins the next: a linker or U+200D.
/// A cluster whose last character is neither joins nothing after it, so a
/// caller can pass over it without reading its neighbour.
pub fn may_link(c: char) -> bool {
    c == ZWJ || is_linker(c)
}

/// Whether `c` may start a cluster that joins the one before it: a
/// consonant or an independent vowel.
pub fn may_follow(c: char) -> bool {
    syllabic(c)
        .is_some_and(|(cat, _)| matches!(cat, Category::Consonant | Category::VowelIndependent))
}

/// Where one cluster's cells lie among its syllable's: from cell `start`
/// of the syllable's `total` cells, `cells` wide, 1 or 2.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct Piece {
    pub start: u8,
    pub cells: u8,
    pub total: u8,
}

impl Piece {
    /// The piece, when it lies inside a syllable of 2 to 28 cells, two for
    /// each of [`SYLLABLE_SCALARS_MAX`], and is 1 or 2 cells wide.
    pub fn new(start: u8, cells: u8, total: u8) -> Option<Piece> {
        let fits = (2..=TOTAL_MAX).contains(&total)
            && (1..=2).contains(&cells)
            && start.checked_add(cells).is_some_and(|end| end <= total);
        fits.then_some(Piece {
            start,
            cells,
            total,
        })
    }

    /// The character that names the piece after its syllable's text:
    /// U+100000 and the piece's place, `start` times 64, plus 32 for a
    /// piece two cells wide, plus `total`.
    pub fn mark(self) -> char {
        let wide = u32::from(self.cells == 2);
        let n = u32::from(self.start) << 6 | wide << 5 | u32::from(self.total);
        char::from_u32(MARK_BASE | n).unwrap_or('\u{10ffff}')
    }

    /// Appends to `out` the key of this piece of the syllable whose text is
    /// `text`: the text, U+001F and the piece's mark. The console makes a
    /// key only for a cell its syllable finder puts in a syllable.
    pub fn key<T: Copy + From<char>>(self, text: &[T], out: &mut Vec<T>) {
        out.extend_from_slice(text);
        out.push(T::from(SEPARATOR));
        out.push(T::from(self.mark()));
    }

    /// The piece `c` names, when it is a piece's mark.
    pub fn of_mark(c: u32) -> Option<Piece> {
        let n = c.checked_sub(MARK_BASE).filter(|&n| n < 1 << 11)?;
        let start = u8::try_from(n >> 6).ok()?;
        let cells = if n & 32 != 0 { 2 } else { 1 };
        let total = u8::try_from(n & 31).ok()?;
        Piece::new(start, cells, total)
    }
}

/// The syllable's text and the piece that `key` names, when `key` is a
/// piece's key ([`Piece::key`]): the text of a syllable, of 2 to
/// [`SYLLABLE_SCALARS_MAX`] scalar values, then U+001F and the piece's
/// mark.
pub fn piece_of(key: &[u32]) -> Option<(&[u32], Piece)> {
    let [text @ .., separator, mark] = key else {
        return None;
    };
    let piece = Piece::of_mark(*mark)?;
    (*separator == u32::from(SEPARATOR) && (2..=SYLLABLE_SCALARS_MAX).contains(&text.len()))
        .then_some((text, piece))
}

/// [`piece_of`] for a key of characters.
pub fn piece_of_chars(key: &[char]) -> Option<(&[char], Piece)> {
    let [text @ .., separator, mark] = key else {
        return None;
    };
    let piece = Piece::of_mark(u32::from(*mark))?;
    (*separator == SEPARATOR && (2..=SYLLABLE_SCALARS_MAX).contains(&text.len()))
        .then_some((text, piece))
}

#[cfg(test)]
#[expect(
    clippy::indexing_slicing,
    clippy::expect_used,
    reason = "a test fails by panicking"
)]
mod tests {
    use super::*;

    fn chars(s: &str) -> Vec<char> {
        s.chars().collect()
    }

    /// Whether each cluster of `clusters` joins the next, in turn.
    fn links(clusters: &[&str]) -> Vec<bool> {
        clusters
            .windows(2)
            .map(|w| joins(&chars(w[0]), &chars(w[1])))
            .collect()
    }

    // ADR-1203 D1: Kannada's virama joins the consonant after it, in ka
    // with ra, ra with ka, the three clusters of stree and the five
    // consonants of kartsnya, whose first cluster ends with a vowel sign
    // and so stays apart
    #[test]
    fn a_kannada_virama_joins_the_consonant_after_it() {
        assert_eq!(links(&["ಕ್", "ರ"]), [true], "ka, virama, ra");
        assert_eq!(links(&["ರ್", "ಕ"]), [true], "ra, virama, ka");
        assert_eq!(links(&["ಸ್", "ತ್", "ರೀ"]), [true, true], "stree");
        assert_eq!(
            links(&["ಕಾ", "ರ್", "ತ್", "ಸ್", "ನ್", "ಯ"]),
            [false, true, true, true, true],
            "kartsnya"
        );
        assert_eq!(
            links(&["ಕ", "ನ್", "ನ", "ಡ"]),
            [false, true, false],
            "kannada"
        );
    }

    // ADR-1203 D1: a consonant with its own stacker links like a virama,
    // in Kannada, Brahmi and Newa; an invisible stacker joins a consonant
    // or an independent vowel, as Masaram Gondi's does
    #[test]
    fn a_stacker_joins_the_letter_after_it() {
        let link = |a: &[char], b: &[char]| joins(a, b);
        assert!(link(&['\u{cf1}'], &['\u{c95}']), "Kannada jihvamuliya, ka");
        assert!(link(&['\u{11003}'], &['\u{11013}']), "Brahmi, ka");
        assert!(link(&['\u{11460}'], &['\u{1140e}']), "Newa, ka");
        assert!(
            link(&['\u{11d0c}', '\u{11d45}'], &['\u{11d0d}']),
            "Masaram Gondi"
        );
        assert!(
            link(&['\u{11d0c}', '\u{11d45}'], &['\u{11d00}']),
            "and its vowel a"
        );
        // a virama joins no independent vowel
        assert!(!link(&['\u{c95}', '\u{ccd}'], &['\u{c85}']), "Kannada a");
    }

    // ADR-1203 D1, after rule GB9c of UAX #29: a linker joins only after a
    // consonant, so x with a Kannada virama joins no ra after it, and a
    // virama alone joins nothing
    #[test]
    fn a_linker_with_no_consonant_before_it_joins_nothing() {
        assert!(!joins(&['x', '\u{ccd}'], &['\u{cb0}']), "x, virama");
        assert!(!joins(&['\u{ccd}'], &['\u{cb0}']), "a virama alone");
        assert!(
            !joins(&['\u{c85}', '\u{ccd}'], &['\u{cb0}']),
            "the vowel a, virama"
        );
        assert!(
            joins(&['\u{c95}', '\u{cbc}', '\u{ccd}'], &['\u{cb0}']),
            "ka, nukta, virama"
        );
    }

    // ADR-1203 D1: U+200D after the virama keeps the join, and U+200C
    // keeps the virama, so nothing joins
    #[test]
    fn a_zero_width_non_joiner_keeps_the_virama() {
        assert!(joins(&['\u{c95}', '\u{ccd}', ZWJ], &['\u{cb0}']));
        assert!(!joins(&['\u{c95}', '\u{ccd}', '\u{200c}'], &['\u{cb0}']));
    }

    // ADR-1203 D1: the two characters must share a script, so a Kannada
    // virama joins no Telugu consonant; a cluster that ends with no
    // linker, and an empty one, join nothing
    #[test]
    fn a_link_across_two_scripts_joins_nothing() {
        assert!(!joins(&['\u{c95}', '\u{ccd}'], &['\u{c15}']), "Telugu ka");
        assert!(!joins(&['\u{c15}', '\u{c4d}'], &['\u{c95}']), "Kannada ka");
        assert!(
            joins(&['\u{c15}', '\u{c4d}'], &['\u{c15}']),
            "Telugu, Telugu"
        );
        assert!(!joins(&['a'], &['\u{c95}']));
        assert!(!joins(&[], &['\u{c95}']));
        assert!(!joins(&['\u{c95}', '\u{ccd}'], &[]));
    }

    // ADR-1203 D1: Devanagari's conjuncts are one cluster already, so no
    // boundary within them joins; between them nothing links
    #[test]
    fn devanagari_clusters_stay_as_they_are() {
        assert_eq!(links(&["न", "म", "स्ते"]), [false, false]);
    }

    // A piece's mark names its place, and only a place inside a syllable
    // of 2 to 28 cells is a piece
    #[test]
    fn a_pieces_mark_names_its_place() {
        for (start, cells, total) in [(0, 1, 2), (1, 1, 2), (2, 2, 4), (26, 2, 28)] {
            let p = Piece::new(start, cells, total).expect("a piece");
            assert_eq!(Piece::of_mark(u32::from(p.mark())), Some(p));
            assert!(u32::from(p.mark()) >= 0x10_0000);
        }
        for (start, cells, total) in [(0, 1, 1), (1, 2, 2), (0, 3, 4), (0, 1, 29)] {
            assert_eq!(
                Piece::new(start, cells, total),
                None,
                "{start} {cells} {total}"
            );
        }
        assert_eq!(Piece::of_mark(0x41), None);
        assert_eq!(Piece::of_mark(0x10_ffff), None);
        let ka_ra: Vec<u32> = [0xc95, 0xccd, 0xcb0].into();
        let mut key = Vec::new();
        let p = Piece::new(1, 1, 2).expect("a piece");
        p.key(&ka_ra, &mut key);
        assert_eq!(key[3..], [0x1f, u32::from(p.mark())]);
        assert_eq!(piece_of(&key), Some((ka_ra.as_slice(), p)));
        assert_eq!(piece_of(&ka_ra), None, "no mark");
        let mut unseparated = ka_ra.clone();
        unseparated.push(u32::from(p.mark()));
        assert_eq!(piece_of(&unseparated), None, "no separator");
        let long = vec![0xc95; SYLLABLE_SCALARS_MAX + 1];
        let mut key = Vec::new();
        p.key(&long, &mut key);
        assert_eq!(piece_of(&key), None, "a text past the bound");
        assert_eq!(SYLLABLE_SCALARS_MAX, 14);
        assert_eq!(key.len(), CLUSTER_SCALARS_MAX as usize + 1, "one past");
    }

    // ADR-1203 D3: a cluster a program writes is no piece's key. Rule GB9b
    // of UAX #29 keeps U+0600, U+0600 and a mark in one cluster, and it
    // names no piece, since no cluster holds the separator
    #[test]
    fn a_programs_cluster_that_ends_with_a_mark_is_no_key() {
        let mark = Piece::new(0, 1, 2).expect("a piece").mark();
        assert_eq!(piece_of_chars(&['\u{600}', '\u{600}', mark]), None);
        let mut key = Vec::new();
        Piece::new(0, 1, 2)
            .expect("a piece")
            .key(&['\u{600}', '\u{600}'], &mut key);
        assert!(piece_of_chars(&key).is_some(), "the console's key");
    }
}
