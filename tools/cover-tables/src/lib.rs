//! The named `cover=` sets of ADR-1200 D1, generated from Unicode's
//! mapping files: each set is the codepoints its standard's file maps to,
//! as sorted ranges, written into vtium-vitrify's `src/cover.rs` with each
//! file's URL, version line and SHA-256 in `provenance.tsv` beside this
//! crate. The files are fetched once, by `cover-tables generate`, into a
//! cache outside the tree; nothing fetches them at build or run time.

use std::fmt::Write as _;

/// One named set and the file it is taken from.
pub struct Source {
    /// The name `cover=` gives it.
    pub name: &'static str,
    /// The constant `src/cover.rs` holds it in.
    pub constant: &'static str,
    pub url: &'static str,
    /// The column of a data line holding the Unicode codepoint, from 0.
    pub column: usize,
}

/// The sets, in the order `src/cover.rs` holds them.
pub const SOURCES: [Source; 3] = [
    Source {
        name: "gbk",
        constant: "GBK",
        url: "https://www.unicode.org/Public/MAPPINGS/VENDORS/MICSFT/WINDOWS/CP936.TXT",
        column: 1,
    },
    Source {
        name: "big5",
        constant: "BIG5",
        url: "https://www.unicode.org/Public/MAPPINGS/OBSOLETE/EASTASIA/OTHER/BIG5.TXT",
        column: 1,
    },
    Source {
        name: "jis-x-0208",
        constant: "JIS_X_0208",
        url: "https://www.unicode.org/Public/MAPPINGS/OBSOLETE/EASTASIA/JIS/JIS0208.TXT",
        column: 2,
    },
];

/// The codepoints a mapping file maps to: in each line that is not a `#`
/// comment, the `column`th of its blank-separated fields before any `#`,
/// in hex with a `0x` prefix. A line without that field, as an undefined
/// byte's, maps nothing.
pub fn codepoints(text: &str, column: usize) -> Result<Vec<u32>, String> {
    let mut out = Vec::new();
    for (line, n) in text.lines().zip(1usize..) {
        let data = line.split('#').next().unwrap_or_default();
        let Some(field) = data.split_whitespace().nth(column) else {
            continue;
        };
        let c = field
            .strip_prefix("0x")
            .or_else(|| field.strip_prefix("0X"))
            .and_then(|h| u32::from_str_radix(h, 16).ok())
            .filter(|&c| char::from_u32(c).is_some())
            .ok_or_else(|| format!("line {n}: {field} is not a codepoint"))?;
        out.push(c);
    }
    out.sort_unstable();
    out.dedup();
    Ok(out)
}

/// Sorted, distinct codepoints as the runs they make, both ends included.
pub fn ranges(codepoints: &[u32]) -> Vec<(u32, u32)> {
    let mut out: Vec<(u32, u32)> = Vec::new();
    for &c in codepoints {
        match out.last_mut() {
            Some((_, end)) if end.checked_add(1) == Some(c) => *end = c,
            _ => out.push((c, c)),
        }
    }
    out
}

/// The file's version, from its header: its `Table version:` and the
/// `Date:` after it, as `2.0, 2011 October 14`.
pub fn version(text: &str) -> Result<String, String> {
    let header = || text.lines().take_while(|l| l.starts_with('#'));
    let value = |line: &str, key: &str| {
        line.split_once(key)
            .map(|(_, v)| v.trim().to_owned())
            .filter(|v| !v.is_empty())
    };
    let table = header()
        .position(|l| l.contains("Table version:"))
        .ok_or("no Table version: line")?;
    let number = header()
        .nth(table)
        .and_then(|l| value(l, "Table version:"))
        .ok_or("an empty Table version:")?;
    let date = header()
        .skip(table)
        .find_map(|l| value(l, "Date:"))
        .ok_or("no Date: after Table version:")?;
    Ok(format!("{number}, {date}"))
}

/// One set generated: its source, the file's version and SHA-256, and its
/// codepoints.
pub struct Generated<'a> {
    pub source: &'a Source,
    pub version: String,
    pub sha256: String,
    pub codepoints: Vec<u32>,
}

/// The ranges written on one line of `src/cover.rs`.
const PER_LINE: usize = 4;

/// `src/cover.rs`: each set's ranges, and the table `cover=` looks a name
/// up in.
pub fn module(sets: &[Generated<'_>]) -> String {
    let mut out = String::from(
        "//! The named `cover=` sets (ADR-1200 D1): each the codepoints its\n\
         //! standard's Unicode mapping file maps to, as sorted ranges, both ends\n\
         //! included. Generated by `cargo run -p vtium-cover-tables -- generate`\n\
         //! (`tools/cover-tables`); do not edit. Each file's URL, version and\n\
         //! SHA-256 are in `tools/cover-tables/provenance.tsv`.\n",
    );
    for set in sets {
        let r = ranges(&set.codepoints);
        let _ = write!(
            out,
            "\n/// `{}`: {} codepoints in {} ranges, from {}.\n#[rustfmt::skip]\npub const {}: &[(u32, u32)] = &[\n",
            set.source.name,
            set.codepoints.len(),
            r.len(),
            set.source.url,
            set.source.constant
        );
        for line in r.chunks(PER_LINE) {
            out.push_str("   ");
            for (a, b) in line {
                let _ = write!(out, " (0x{a:05x}, 0x{b:05x}),");
            }
            out.push('\n');
        }
        out.push_str("];\n");
    }
    let _ = write!(
        out,
        "\n/// Each set by the name `cover=` gives it.\npub const SETS: [(&str, &[(u32, u32)]); {}] = [\n",
        sets.len()
    );
    for set in sets {
        let _ = writeln!(out, "    ({:?}, {}),", set.source.name, set.source.constant);
    }
    out.push_str("];\n");
    out
}

/// `provenance.tsv`: each set's name, URL, version, SHA-256 and count of
/// codepoints.
pub fn provenance(sets: &[Generated<'_>]) -> String {
    let mut out = String::from(
        "# Each named cover= set's source, fetched once by tools/cover-tables:\n\
         # NAME URL VERSION SHA256 CODEPOINTS. Unicode's terms of use cover the files.\n",
    );
    for set in sets {
        let _ = writeln!(
            out,
            "{}\t{}\t{}\t{}\t{}",
            set.source.name,
            set.source.url,
            set.version,
            set.sha256,
            set.codepoints.len()
        );
    }
    out
}

/// The SHA-256 `provenance` pins for the set `name`, if it names one.
pub fn pinned<'a>(provenance: &'a str, name: &str) -> Option<&'a str> {
    provenance
        .lines()
        .filter(|l| !l.starts_with('#'))
        .find_map(|l| {
            let f: Vec<&str> = l.split('\t').collect();
            (f.first() == Some(&name))
                .then(|| f.get(3).copied())
                .flatten()
        })
}

#[cfg(test)]
mod tests {
    use super::*;

    const FILE: &str = "# Date: 2015-12-02 23:50:00 GMT [KW]\n\
        #\tName:             test to Unicode\n\
        #\tTable version:    2.0\n\
        #\tTable format:     Format A\n\
        #\tDate:             2011 October 14 (header updated: 2015 December 02)\n\
        #\n\
        0x8140\t0x2121\t0x3000\t# IDEOGRAPHIC SPACE\n\
        0x8141\t0x2122\t0x3001\t# IDEOGRAPHIC COMMA\n\
        0x81CA\t0x224C\t0x00AC\t# NOT SIGN\n\
        0x81CB\t0x224D\t0x3001\t# a second byte to one codepoint\n\
        0xFF\t\t#UNDEFINED\n\
        \n\
        0x8142\t0x2123\t0x3003\n";

    #[test]
    fn a_mapping_file_gives_its_columns_codepoints_once_each_sorted() {
        assert_eq!(codepoints(FILE, 2).unwrap(), [0xac, 0x3000, 0x3001, 0x3003]);
        assert_eq!(
            codepoints(FILE, 1).unwrap(),
            [0x2121, 0x2122, 0x2123, 0x224c, 0x224d]
        );
        let e = codepoints("0x8140\t0xD800\n", 1).unwrap_err();
        assert_eq!(e, "line 1: 0xD800 is not a codepoint");
        assert!(codepoints("0x8140\tzz\n", 1).is_err());
    }

    #[test]
    fn codepoints_make_their_runs() {
        assert_eq!(
            ranges(&[0xac, 0x3000, 0x3001, 0x3003]),
            [(0xac, 0xac), (0x3000, 0x3001), (0x3003, 0x3003)]
        );
        assert_eq!(ranges(&[]), []);
    }

    #[test]
    fn the_version_is_the_table_version_and_the_date_after_it() {
        assert_eq!(
            version(FILE).unwrap(),
            "2.0, 2011 October 14 (header updated: 2015 December 02)"
        );
        assert!(version("#\tDate: 2011\n0x1 0x2\n").is_err());
    }

    #[test]
    fn the_module_and_provenance_name_each_set() {
        let set = Generated {
            source: &SOURCES[2],
            version: "2.0, 2011".to_owned(),
            sha256: "ab".repeat(32),
            codepoints: vec![0xac, 0x3000, 0x3001, 0x3003, 0x3005, 0x3007],
        };
        let m = module(std::slice::from_ref(&set));
        assert!(m.contains(
            "/// `jis-x-0208`: 6 codepoints in 5 ranges, from https://www.unicode.org/Public/MAPPINGS/OBSOLETE/EASTASIA/JIS/JIS0208.TXT.\n"
        ));
        assert!(m.contains(
            "    (0x000ac, 0x000ac), (0x03000, 0x03001), (0x03003, 0x03003), (0x03005, 0x03005),\n    (0x03007, 0x03007),\n];\n"
        ));
        assert!(m.ends_with("    (\"jis-x-0208\", JIS_X_0208),\n];\n"));
        let p = provenance(std::slice::from_ref(&set));
        let line = format!(
            "jis-x-0208\t{}\t2.0, 2011\t{}\t6\n",
            SOURCES[2].url,
            "ab".repeat(32)
        );
        assert!(p.ends_with(&line), "{p}");
        assert_eq!(pinned(&p, "jis-x-0208"), Some("ab".repeat(32).as_str()));
        assert_eq!(pinned(&p, "big5"), None);
    }
}
