/// The font a screen is drawn with.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum FontKind {
    /// The built-in unifont at 16 pixels, 8x16 cells.
    Unifont,
    /// The built-in font at 16 pixels as the console draws it for a display
    /// with no font set, through the console's own face for it
    /// (`vtium::font::Chosen::BUILTINS`): GNU Unifont in 8x16 cells, which
    /// in a build with the bidi feature draws a joined Arabic letter by the
    /// Arabic presentation form of its joined form (ADR-1004 D6).
    Builtin,
    /// Sprites only, in the cell size of the outline font the golden was
    /// drawn with: the screen holds nothing but sprites and spaces, which draw
    /// the same in any font of that cell, so the golden judges it while
    /// vtium has no outline font (vtium/vtium#23).
    Sprites { width: u32, height: u32 },
    /// A PSF font `tools/testfont` writes, read through vtium-font's PSF
    /// loader at its own size.
    Psf(TestFont),
    /// A PSF font `tools/testfont` writes, its glyphs generated by
    /// vtium-config's engine from a frit naming it (ADR-1301 D2), with
    /// `fill`, a built-in set, filling the characters the font lacks, and
    /// drawn at the font's own cell.
    Set {
        font: TestFont,
        fill: Option<&'static str>,
    },
    /// The vitrified set [`crate::colorset`] builds, unifont's ASCII in a
    /// 1-bit strike and color glyphs in an RGBA strike at 8x16, drawn for
    /// cells `height` pixels high (vtium/vtium#23).
    ColorSet { height: u32 },
    /// A frit of the built-in set `builtin` alone, its glyphs generated by
    /// vtium-config's engine in a cell of `width` by `height`, as the
    /// helper generates a frit in the cell it states: each glyph scaled by
    /// the largest whole factor that fits, centred across and on the
    /// cell's bottom rows.
    Frit {
        builtin: &'static str,
        width: u32,
        height: u32,
    },
    /// The test frit of outline fonts [`crate::fonts`] fetches (ADR-1503
    /// D9), at [`crate::fonts::HEIGHT`] pixels in the cell its first
    /// source gives there, drawn as the console draws a frit: the glyphs
    /// vtium-config's engine generates for what the screen shows, and the
    /// built-in font for what no source holds. Without `color`, the frit
    /// leaves out its color emoji font. With a `spacing`, the frit's
    /// `line-spacing=` makes each row taller (ADR-1302 D13).
    Outline {
        color: bool,
        spacing: Option<Spacing>,
    },
    /// A frit of `fonts`, its rows made taller by `spacing` when it is set
    /// (ADR-1302 D13), drawn as the console draws a frit, as for
    /// [`FontKind::Outline`]. The screen is drawn once for each of
    /// `takes`, and the drawings are stacked from the top in their order.
    Ink {
        takes: &'static [Take],
        spacing: Option<Spacing>,
        fonts: InkFonts,
    },
}

/// The fonts a [`FontKind::Ink`] screen draws with.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum InkFonts {
    /// The ink test font [`crate::inkfont`] builds in memory, alone in a
    /// frit: glyphs whose ink passes their cells by known amounts.
    Test,
    /// The test frit of outline fonts [`crate::fonts`] fetches, without
    /// its color emoji font: DejaVu Sans Mono's four faces, then Noto Sans
    /// CJK, whose ink passes their cells as those fonts draw it.
    DejaVu,
}

/// One drawing of a [`FontKind::Ink`] screen: at `height` pixels, with
/// `tail` fed after the screen's bytes, and in the blink phase `phase`.
/// The terminal hides the cursor before the bytes, so a tail that shows
/// the cursor draws it, in its blink phase that shows it.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Take {
    pub height: u32,
    pub tail: &'static [u8],
    pub blink_hidden: bool,
}

impl Take {
    /// A drawing at `height` pixels with nothing fed after the bytes, the
    /// cursor hidden and blinking text shown.
    pub const fn at(height: u32) -> Take {
        Take {
            height,
            tail: b"",
            blink_hidden: false,
        }
    }
}

/// The blink phases a screen's frames are drawn in: whether the cursor's
/// shows it, whether blinking text, SGR 5, is in its hidden phase, and
/// whether rapidly blinking text, SGR 6, is in its own.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct Phase {
    pub cursor_on: bool,
    pub blink_hidden: bool,
    pub rapid_hidden: bool,
}

impl Phase {
    /// What a frame of a terminal of default background `background`
    /// needs beyond the terminal's state, in this phase.
    pub(crate) fn state(self, background: Rgb) -> DrawState {
        DrawState {
            cursor_on: self.cursor_on,
            blink_hidden: self.blink_hidden,
            rapid_hidden: self.rapid_hidden,
            background,
            ..DrawState::default()
        }
    }
}

/// Line spacing a spaced outline screen sets, and the rows it must add:
/// `percent` goes in the frit's `line-spacing=`, and `above` and `below`
/// are the rows the screen expects the console to add above and below
/// the text band, stated by hand so that [`crate::bands::check`] holds the
/// console's rounding and split to them (ADR-1302 D13).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Spacing {
    pub percent: u32,
    pub above: u32,
    pub below: u32,
}

/// The PSF fonts the small displays draw with (vtium/vtium#75).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum TestFont {
    /// `vtium-test-8x8.psf`, PSF2.
    Small8x8,
    /// `vtium-test-8x16.psf`, PSF1.
    Small8x16,
}

impl TestFont {
    /// The font's file, as `tools/testfont` writes it.
    pub fn bytes(self) -> Result<Vec<u8>, String> {
        match self {
            TestFont::Small8x8 => vtium_testfont::small8x8()?.psf2(),
            TestFont::Small8x16 => vtium_testfont::small8x16()?.psf1(),
        }
    }

    /// The name `tools/testfont` gives the font's file.
    fn file(self) -> &'static str {
        match self {
            TestFont::Small8x8 => "vtium-test-8x8.psf",
            TestFont::Small8x16 => "vtium-test-8x16.psf",
        }
    }

    /// The glyphs vtium-config's engine, the one the helper runs
    /// (ADR-1301 D2), draws at the font's own cell from a frit naming the
    /// font, then `fill`, a built-in set: every glyph the frit gives, as a
    /// set's bytes. The engine reads a `file:` source from disk, so the font
    /// is written to a scratch file this call names and removed once read.
    pub fn generate(self, fill: Option<&str>) -> Result<Vec<u8>, String> {
        use std::sync::atomic::{AtomicU64, Ordering};
        use vtium_config::serve::{Engine, FritText, Paths};
        static CALLS: AtomicU64 = AtomicU64::new(0);
        let bytes = self.bytes()?;
        let cell = Psf::parse(&bytes)
            .map_err(|e| format!("{self:?}: {e}"))?
            .cell();
        let path = std::env::temp_dir().join(format!(
            "vtium-tier2-{}-{}-{}",
            std::process::id(),
            CALLS.fetch_add(1, Ordering::Relaxed),
            self.file()
        ));
        std::fs::write(&path, &bytes).map_err(|e| format!("{}: {e}", path.display()))?;
        let mut text = format!("source=file:{}\n", path.display());
        if let Some(fill) = fill {
            text.push_str(&format!("source=builtin:{fill}\n"));
        }
        let frit = FritText {
            name: self.file().trim_end_matches(".psf").to_owned(),
            text,
        };
        let engine = Engine::load(&frit, &Paths::default(), None);
        let _ = std::fs::remove_file(&path);
        let engine = engine?;
        engine
            .draw(cell, engine.coverage())?
            .ok_or_else(|| engine.none_at(cell))
    }
}

/// A face with a cell and no glyphs but the space, under the sprites.
#[derive(Clone, Copy, Debug)]
pub struct SpritesOnly(Cell);

impl Face for SpritesOnly {
    fn cell(&self) -> Cell {
        self.0
    }

    fn size_step(&self) -> u32 {
        self.0.height
    }

    fn has_glyph(&self, c: char) -> bool {
        c == ' '
    }

    fn draw(&self, cluster: &[char], _style: FontStyle) -> Option<Glyph> {
        (cluster == [' ']).then(|| Glyph::mask(self.0.width, self.0.height))?
    }
}

/// A configured decoration color: `underline-color` or `strike-color`
/// as an index into the palette or as a color.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum DecoSpec {
    Index(u8),
    Rgb(u8, u8, u8),
}

/// The decoration colors a screen configures; an absent one follows the
/// cell's foreground.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct Decorations {
    pub underline: Option<DecoSpec>,
    pub strike: Option<DecoSpec>,
    /// `force-decoration-colors`: the configured underline color wins over
    /// SGR 58's.
    pub force: bool,
}

impl Decorations {
    /// The colors as the renderer takes them: an index resolved through
    /// each frame's palette, resolved again on every frame.
    fn colors(&self) -> DecorationColors {
        let color = |spec: Option<DecoSpec>| match spec {
            None => DecoColor::Foreground,
            Some(DecoSpec::Index(i)) => DecoColor::Indexed(i),
            Some(DecoSpec::Rgb(r, g, b)) => DecoColor::Rgb(Rgb::new(r, g, b)),
        };
        DecorationColors {
            underline: color(self.underline),
            strike: color(self.strike),
            force: self.force,
        }
    }
}

/// A line of text vtium builds as it runs, such as a notice: a function of
/// the console's that gives it, so a reworded notice moves its golden.
pub type Words = fn() -> Result<String, String>;

/// The notice of a screen the display guard lights for it alone, built as
/// vtium builds it: the panic screen's report, or a line of text.
pub type Alone = fn() -> Result<vtium_render::Notice, String>;

/// What vtium draws of its own over a screen's last frame (ADR-1401 D5,
/// D7), as a head puts it together: one box across the top holding the
/// on-screen display's full line and the notices beneath it, in the
/// notices' colors while a notice is in it, and the on-screen display's
/// dot in the grid's top-right cell, in the on-screen display's colors.
/// The console's own overlay draws it, with the screen's font, outside the
/// terminal's cells.
#[derive(Clone, Copy, Debug)]
pub struct Overlay {
    /// `osd = full`'s line.
    pub line: Option<Words>,
    /// The notices, oldest first, at most the [`NOTICES_MAX`] a head
    /// shows.
    pub notices: &'static [Words],
    /// `osd = minimal`'s dot.
    pub mark: Option<Mark>,
    /// One of the example configuration's other color schemes; `None` for
    /// the colors vtium draws with no color key set.
    pub scheme: Option<&'static Scheme>,
}

impl Overlay {
    /// The console's overlay of this one, built as a head builds its own,
    /// refused past the [`NOTICES_MAX`] notices a head shows.
    pub fn console(&self) -> Result<vtium::term::Overlay, String> {
        if self.notices.len() > NOTICES_MAX {
            return Err(format!(
                "{} notices, where a head shows at most {NOTICES_MAX}",
                self.notices.len()
            ));
        }
        let line = self.line.map(|l| l()).transpose()?;
        let notices = self
            .notices
            .iter()
            .map(|n| n())
            .collect::<Result<Vec<_>, _>>()?;
        let notices: Vec<&str> = notices.iter().map(String::as_str).collect();
        let colors = self.scheme.map(OverlayColors::scheme).unwrap_or_default();
        Ok(vtium::term::Overlay::new(
            line.as_deref(),
            &notices,
            self.mark,
            colors,
        ))
    }
}

/// What a picture screen feeds before one of its frames.
pub type Pictures = fn(&mut Feed) -> Result<(), String>;

/// What a picture screen's pictures are fed through before one of its
/// frames: the terminal, the frame they come before, and the cell size
/// in pixels the pictures are made in.
pub struct Feed<'a> {
    term: &'a mut Terminal,
    /// The frame the pictures come before: 0 after the screen's bytes;
    /// for a screen with a second part 1, 2 after the second part, and 3.
    pub frame: u32,
    /// The cell the terminal makes pictures in, as it tells programs.
    pub cell: (u32, u32),
}

impl Feed<'_> {
    /// Feeds `bytes` to the terminal, as a program's output reaches it.
    pub fn bytes(&mut self, bytes: &[u8]) -> Result<(), String> {
        feed(self.term, bytes)
    }

    /// Makes the pictures that follow in cells of `cell` pixels, as a
    /// host sets the cell size it tells programs; a picture keeps the
    /// cell it was made in, and is drawn scaled to the font's cells.
    pub fn made_in(&mut self, (width, height): (u32, u32)) -> Result<(), String> {
        self.cell = (width, height);
        self.term
            .screen_mut()
            .set_image_cell(width, height)
            .map_err(|e| format!("the picture cell {width}x{height}: {e:?}"))
    }
}

/// One screen of tier 2.
#[derive(Clone, Copy, Debug)]
pub struct Screen {
    pub name: &'static str,
    /// What the screen shows and what correct looks like: the report's
    /// caption.
    pub desc: &'static str,
    pub bytes: &'static [u8],
    /// The second part, fed after two frames; two more frames follow.
    pub next: Option<&'static [u8]>,
    pub cols: usize,
    pub rows: usize,
    /// The display's size in pixels before it is turned; `None` for the
    /// grid's own size.
    pub display: Option<(u32, u32)>,
    pub orientation: Orientation,
    pub font: FontKind,
    pub width_method: WidthMethod,
    pub decorations: Decorations,
    /// The display's depth: a 1-bit screen is drawn in black and white.
    pub depth: Depth,
    /// vtium's own drawing over the last frame.
    pub overlay: Option<Overlay>,
    /// The notice of the screen the display guard lights for a notice
    /// alone (ADR-1401 D7, D9), drawn over the last frame as that screen
    /// draws it, the panic screen's report among them.
    pub alone: Option<Alone>,
    /// The cell under the pointer, a column and a row, set after the
    /// bytes: the link there draws hovered (ADR-1002, "Drawing").
    pub pointer: Option<(usize, usize)>,
    /// Ctrl held with the pointer: the hovered link's address shows on
    /// the overlay row (ADR-1002, "Drawing").
    pub ctrl: bool,
    /// The pictures, fed with the terminal's sixel and kitty handlers on
    /// (`crate::pictures`): before the first frame, after the bytes, and,
    /// for a screen with a second part, before each later frame too, the
    /// third after the second part.
    pub pictures: Option<Pictures>,
    /// The cell size the terminal tells programs and makes its pictures
    /// in, when it is not the font's: a picture made in a larger cell is
    /// drawn smaller.
    pub made_cell: Option<(u32, u32)>,
    /// A selection from one cell to another, a column and a row each, made
    /// after the pictures.
    pub selection: Option<((usize, usize), (usize, usize))>,
    /// The largest texture side the GPU path's pictures use, set small so
    /// a picture is held in tiles (ADR-1303 D2).
    pub largest_texture: Option<u32>,
    /// Bytes fed after `bytes` and before the pictures, set by a
    /// [`Take`].
    pub tail: &'static [u8],
    /// The blink phases every frame is drawn in.
    pub phase: Phase,
}

impl Screen {
    /// A screen of `cols` by `rows` in unifont, unturned, sized to its
    /// grid, with no second part.
    pub const fn new(
        name: &'static str,
        desc: &'static str,
        bytes: &'static [u8],
        cols: usize,
        rows: usize,
    ) -> Screen {
        Screen {
            name,
            desc,
            bytes,
            next: None,
            cols,
            rows,
            display: None,
            orientation: Orientation::Normal,
            font: FontKind::Unifont,
            width_method: WidthMethod::Unicode,
            decorations: Decorations {
                underline: None,
                strike: None,
                force: false,
            },
            depth: Depth::Color,
            overlay: None,
            alone: None,
            pointer: None,
            ctrl: false,
            pictures: None,
            made_cell: None,
            selection: None,
            largest_texture: None,
            tail: b"",
            phase: Phase {
                cursor_on: false,
                blink_hidden: false,
                rapid_hidden: false,
            },
        }
    }
}

/// The ways a screen is drawn, each of which must give the same bytes.
fn configs(orientation: Orientation) -> [(&'static str, Config); 4] {
    let base = Config {
        orientation,
        ..Config::default()
    };
    [
        ("default", base),
        (
            "a cache of no glyphs",
            Config {
                budgets: Some(Budgets::glyphs(0)),
                ..base
            },
        ),
        (
            "the performance profile",
            Config {
                profile: Profile::Performance,
                ..base
            },
        ),
        (
            "8-bit glyphs at their drawn size",
            Config {
                storage: Storage {
                    bits: false,
                    unscaled: false,
                },
                ..base
            },
        ),
    ]
}

/// What draws a screen's frames for one configuration: the CPU path
/// ([`Cpu`]), or the GPU path (`crate::gpu`).
pub trait Paint {
    /// Draws `screen` with fonts `make_font` makes, in `config`, and gives
    /// the picture the display shows last.
    fn paint<F: Face, M: Fn() -> Font<F>>(
        &mut self,
        screen: &Screen,
        make_font: &M,
        config: Config,
    ) -> Result<Image, String>;
}

/// The CPU path, as the console draws on it: each frame into a buffer in
/// memory.
pub struct Cpu;

impl Paint for Cpu {
    fn paint<F: Face, M: Fn() -> Font<F>>(
        &mut self,
        screen: &Screen,
        make_font: &M,
        config: Config,
    ) -> Result<Image, String> {
        draw_config(screen, make_font, config)
    }
}

/// Draws `screen` on the CPU path, and checks it draws the same in every
/// configuration.
pub fn draw(screen: &Screen) -> Result<Image, String> {
    draw_on(screen, &mut Cpu)
}

/// Draws `screen` through `painter`, and checks it draws the same in every
/// configuration.
pub fn draw_on(screen: &Screen, painter: &mut impl Paint) -> Result<Image, String> {
    let p = painter;
    match screen.font {
        FontKind::Unifont => draw_with(screen, || Font::new(Unifont::new(16)), p),
        FontKind::Builtin => {
            let face = || vtium::font::Chosen::BUILTINS.face(16, "C");
            face().ok_or("the console has no built-in face at 16 pixels")?;
            draw_with(
                screen,
                || Font::new(face().expect("a face, as it was before")),
                p,
            )
        }
        FontKind::Sprites { width, height } => {
            draw_with(screen, || Font::new(SpritesOnly(Cell { width, height })), p)
        }
        FontKind::Psf(font) => {
            let psf = Psf::parse(&font.bytes()?).map_err(|e| format!("{font:?}: {e}"))?;
            draw_with(screen, || Font::new(psf.clone()), p)
        }
        FontKind::Set { font, fill } => {
            let set =
                Set::from_bytes(font.generate(fill)?).map_err(|e| format!("{font:?}: {e}"))?;
            let set = Arc::new(set);
            let height = set.cells().first().map_or(16, |c| c.height);
            let face = SetFace::new(set, height).ok_or_else(|| format!("{font:?}: no strike"))?;
            draw_with(screen, || Font::new(face.clone()), p)
        }
        FontKind::ColorSet { height } => {
            let face = SetFace::new(crate::colorset::set()?, height)
                .ok_or("the color set has no strike")?;
            draw_with(screen, || Font::new(face.clone()), p)
        }
        FontKind::Frit {
            builtin,
            width,
            height,
        } => {
            use vtium_config::serve::{Engine, FritText, Paths};
            // a frit may not take a built-in set's name
            let frit = FritText {
                name: format!("{builtin}-{width}x{height}"),
                text: format!("source=builtin:{builtin}\n"),
            };
            let engine = Engine::load(&frit, &Paths::default(), None)?;
            let cell = Cell { width, height };
            let bytes = engine
                .draw(cell, engine.coverage())?
                .ok_or_else(|| engine.none_at(cell))?;
            let set = Arc::new(Set::from_bytes(bytes).map_err(|e| format!("{builtin}: {e}"))?);
            let face = SetFace::new(set, height).ok_or_else(|| format!("{builtin}: no strike"))?;
            draw_with(screen, || Font::new(face.clone()), p)
        }
        FontKind::Outline { color, spacing } => {
            let dir = crate::fonts::cache_dir();
            let percent = spacing.map_or(0, |s| s.percent);
            let chosen = crate::fonts::chosen(&dir, (color, percent), |cell| shown(screen, cell))?;
            crate::fonts::face(&chosen)?;
            let img = draw_with(
                screen,
                || Font::new(crate::fonts::face(&chosen).expect("a face, as it was before")),
                p,
            )?;
            if let Some(spacing) = spacing {
                spaced_as_plain(screen, color, spacing, &img)?;
            }
            Ok(img)
        }
        FontKind::Ink {
            takes,
            spacing,
            fonts,
        } => {
            let percent = spacing.map_or(0, |s| s.percent);
            let fetched = crate::fonts::cache_dir();
            let (name, text, dir) = match fonts {
                InkFonts::Test => {
                    let dir = crate::inkfont::dir()?;
                    ("tier2-ink", crate::inkfont::frit_text(dir, percent), dir)
                }
                InkFonts::DejaVu => {
                    crate::fonts::check(&fetched)?;
                    let text = crate::fonts::frit_text(&fetched, false, percent);
                    ("tier2-outline-mono", text, fetched.as_path())
                }
            };
            let mut drawn = Vec::new();
            for take in takes {
                let one = Screen {
                    tail: take.tail,
                    phase: Phase {
                        cursor_on: true,
                        blink_hidden: take.blink_hidden,
                        rapid_hidden: take.blink_hidden,
                    },
                    ..*screen
                };
                let chosen =
                    crate::fonts::chosen_frit((name, text.clone()), dir, take.height, |cell| {
                        shown(&one, cell)
                    })?;
                crate::fonts::face_at(&chosen, take.height)?;
                let img = draw_with(
                    &one,
                    || {
                        Font::new(
                            crate::fonts::face_at(&chosen, take.height)
                                .expect("a face, as it was before"),
                        )
                    },
                    p,
                )
                .map_err(|e| format!("at {} pixels: {e}", take.height))?;
                drawn.push(img);
            }
            stack(&drawn)
        }
    }
}

/// `drawn` stacked from the top, each at the left, and grey to the right
/// of a drawing narrower than the widest, so no padding looks like a cell.
fn stack(drawn: &[Image]) -> Result<Image, String> {
    const PAD: [u8; 3] = [0x80, 0x80, 0x80];
    let width = drawn.iter().map(Image::width).max().unwrap_or(0);
    let mut rgb = Vec::new();
    for img in drawn {
        for y in 0..img.height() {
            rgb.extend_from_slice(img.row(y));
            for _ in img.width()..width {
                rgb.extend_from_slice(&PAD);
            }
        }
    }
    let height = drawn.iter().map(Image::height).sum();
    Image::new(width, height, rgb).ok_or_else(|| "no drawing to stack".to_owned())
}

/// Checks that `img`, `screen` drawn with `spacing`, holds in each of
/// its rows the text band of the same screen drawn with no spacing, at
/// the rows `spacing` says the console adds (ADR-1302 D13): a cell holding
/// a sprite, which stretches to the whole taller cell, is not compared.
fn spaced_as_plain(
    screen: &Screen,
    color: bool,
    spacing: Spacing,
    img: &Image,
) -> Result<(), String> {
    if screen.next.is_some() || screen.pictures.is_some() || screen.display.is_some() {
        return Err("a spaced screen is one frame of text sized to its grid".to_owned());
    }
    let plain = Screen {
        font: FontKind::Outline {
            color,
            spacing: None,
        },
        ..*screen
    };
    let unspaced = draw(&plain)?;
    let term = terminal(screen, (0, 0))?;
    let frame = term.screen().frame(term.palette(), Age::NEVER);
    let sprites: Vec<Vec<bool>> = (0..screen.rows)
        .map(|row| {
            let mut at = vec![false; screen.cols];
            for (col, cell) in frame.cells(row).enumerate().take(screen.cols) {
                at[col] = matches!(cell.glyph, Text::Char(c) if vtium_font::sprite::has(c));
            }
            at
        })
        .collect();
    crate::bands::check(
        img,
        &unspaced,
        (screen.cols, screen.rows),
        spacing,
        |col, row| sprites[row][col],
    )
    .map_err(|e| format!("{}: {e}", screen.name))
}

/// What `screen` shows in a font of `cell` before each frame it draws,
/// merged style by style, as the console reads what its displays show to
/// ask the helper for their glyphs: in each style a cell draws its glyph
/// in, bold, italic, both or neither, the characters, every character of
/// a cluster among them, and the clusters whole, each sorted and once,
/// white space left out. The regular style comes first.
pub fn shown(screen: &Screen, cell: Cell) -> Result<Vec<Shown>, String> {
    let made = picture_cell(screen, cell);
    let mut term = terminal(screen, made)?;
    let mut all = vec![Shown::default()];
    let read = |term: &Terminal, all: &mut Vec<Shown>| {
        vtium::deferred::read_shown(&term.screen().frame(term.palette(), Age::NEVER), all);
    };
    read(&term, &mut all);
    if let Some(next) = screen.next {
        later(screen, &mut term, 1, made)?;
        read(&term, &mut all);
        feed(&mut term, next)?;
        later(screen, &mut term, 2, made)?;
        read(&term, &mut all);
        later(screen, &mut term, 3, made)?;
        read(&term, &mut all);
    }
    vtium::deferred::settle(&mut all);
    Ok(all)
}

fn draw_with<F: Face>(
    screen: &Screen,
    font: impl Fn() -> Font<F>,
    painter: &mut impl Paint,
) -> Result<Image, String> {
    let mut first: Option<(&str, Image)> = None;
    for (name, config) in configs(screen.orientation) {
        let img = painter.paint(screen, &font, config)?;
        match &first {
            None => first = Some((name, img)),
            Some((_, want)) if *want == img => {}
            Some((base, _)) => {
                return Err(format!(
                    "drawn with {name}, it differs from the {base} drawing"
                ));
            }
        }
    }
    first
        .map(|(_, img)| img)
        .ok_or_else(|| "no configuration".to_owned())
}

/// A display of two buffers, each knowing the frame it holds.
struct Display {
    buffers: [Canvas; 2],
    /// The swap after which each buffer was shown, if it has been.
    shown: [Option<u64>; 2],
    back: usize,
    swaps: u64,
}

impl Display {
    fn new(width: u32, height: u32) -> Display {
        // new memory holds anything: what is drawn must not depend on it
        Display {
            buffers: [
                Canvas::new(width, height, 0x00a5_5a3c),
                Canvas::new(width, height, 0x003c_5aa5),
            ],
            shown: [None; 2],
            back: 0,
            swaps: 0,
        }
    }

    /// The back buffer's age: 0 when it was never shown, else how many
    /// frames back the frame it holds is.
    fn age(&self) -> u32 {
        self.shown[self.back].map_or(0, |n| u32::try_from(self.swaps - n + 1).unwrap_or(u32::MAX))
    }

    /// Draws the terminal's frame into the back buffer and swaps when the
    /// frame drew anything, as a display does.
    fn frame<F: Face>(
        &mut self,
        r: &mut Renderer<F>,
        (term, phase): (&mut Terminal, Phase),
        since: &mut Age,
    ) {
        let state = phase.state(term.palette().bg());
        let age = self.age();
        let drew = {
            let frame = term.screen().frame(term.palette(), *since);
            !r.draw(&frame, &mut self.buffers[self.back], age, &state)
                .damage
                .is_empty()
        };
        *since = term.screen_mut().checkpoint();
        if drew {
            self.swaps += 1;
            self.shown[self.back] = Some(self.swaps);
            self.back ^= 1;
        }
    }

    /// The buffer shown last.
    fn front(&self) -> &Canvas {
        &self.buffers[self.back ^ 1]
    }
}

fn feed(term: &mut Terminal, mut bytes: &[u8]) -> Result<(), String> {
    while !bytes.is_empty() {
        let taken = term.input(bytes);
        let replies = term.take_replies();
        if taken == 0 && replies.is_empty() {
            return Err("the terminal stopped taking input".to_owned());
        }
        bytes = &bytes[taken..];
    }
    Ok(())
}

/// Refuses a sprites-only screen holding a character that is not a sprite
/// or a space, a combining mark on either included: an outline font
/// would draw it, and vtium does not have one.
fn check_sprites<F: Face>(font: &Font<F>, term: &Terminal) -> Result<(), String> {
    let frame = term.screen().frame(term.palette(), Age::NEVER);
    for row in 0..frame.rows() {
        for col in 0..frame.cols() {
            let mut buf = [0u8; 4];
            let text = match frame.cell(row, col).map(|c| c.glyph) {
                Some(Text::Char(c)) => &*c.encode_utf8(&mut buf),
                Some(Text::Cluster(s)) => s,
                _ => continue,
            };
            if let Some(c) = text.chars().find(|&c| !font.has_glyph(c)) {
                return Err(format!(
                    "cell {col},{row} holds U+{:04X}, which only an outline font draws",
                    u32::from(c)
                ));
            }
        }
    }
    Ok(())
}

/// The configuration `config` for `screen`: its decoration colors and its
/// display's depth.
pub(crate) fn screen_config(screen: &Screen, config: Config) -> Config {
    Config {
        decorations: screen.decorations.colors(),
        depth: screen.depth,
        ..config
    }
}

/// The cell `screen`'s pictures are made in, in a font of `cell`.
pub(crate) fn picture_cell(screen: &Screen, cell: Cell) -> (u32, u32) {
    screen.made_cell.unwrap_or((cell.width, cell.height))
}

/// `screen`'s terminal with its bytes fed and, for a picture screen, its
/// pictures, made in cells of `made`, before the first frame.
fn terminal(screen: &Screen, made: (u32, u32)) -> Result<Terminal, String> {
    let mut term = Terminal::new(screen.cols, screen.rows, 0);
    // as a host sets it at start: the screen's method, and what RIS
    // returns to
    term.set_default_width_method(screen.width_method);
    term.screen_mut().set_width_method(screen.width_method);
    // the cursor's blink state is not part of what is compared
    feed(&mut term, b"\x1b[?25l")?;
    feed(&mut term, screen.bytes)?;
    feed(&mut term, screen.tail)?;
    if let Some(pictures) = screen.pictures {
        term.screen_mut().set_image_limit(1 << 26);
        term.set_image_switches(Switches {
            sixel: true,
            kitty: true,
            iterm2: false,
        });
        term.set_image_handler(ImageString::Sixel, Some(Box::new(Sixel::default())));
        term.set_image_handler(ImageString::Kitty, Some(Box::new(Kitty::default())));
        run_pictures(pictures, &mut term, 0, made)?;
        if term
            .screen()
            .frame(term.palette(), Age::NEVER)
            .placements()
            .is_empty()
        {
            return Err("the screen's pictures placed nothing".to_owned());
        }
    }
    Ok(term)
}

/// Feeds `pictures` before frame `frame`, made in cells of `made`, and
/// leaves the terminal making pictures in that cell again.
fn run_pictures(
    pictures: Pictures,
    term: &mut Terminal,
    frame: u32,
    made: (u32, u32),
) -> Result<(), String> {
    let mut f = Feed {
        term,
        frame,
        cell: made,
    };
    f.made_in(made)?;
    pictures(&mut f)?;
    f.made_in(made)
}

/// Feeds `screen`'s pictures before its later frame `frame`, 1 to 3, made
/// in cells of `made`; a screen without pictures feeds nothing.
pub(crate) fn later(
    screen: &Screen,
    term: &mut Terminal,
    frame: u32,
    made: (u32, u32),
) -> Result<(), String> {
    match screen.pictures {
        Some(pictures) => run_pictures(pictures, term, frame, made),
        None => Ok(()),
    }
}

/// `screen`'s terminal with its bytes and first pictures fed and its
/// pointer set, and its display's size, turned, for `font`.
pub(crate) fn prepare<F: Face>(
    screen: &Screen,
    font: &Font<F>,
) -> Result<(Terminal, u32, u32), String> {
    let mut term = terminal(screen, picture_cell(screen, font.cell()))?;
    if let Some(((c0, r0), (c1, r1))) = screen.selection {
        term.screen_mut().select_start(c0, r0);
        term.screen_mut().select_to(c1, r1);
    }
    if let Some(at) = screen.pointer {
        term.screen_mut().set_pointer(Some(at), screen.ctrl);
    }
    if matches!(screen.font, FontKind::Sprites { .. }) {
        check_sprites(font, &term)?;
    }
    let cell = font.cell();
    let (w, h) = screen.display.unwrap_or((
        cell.width * screen.cols as u32,
        cell.height * screen.rows as u32,
    ));
    let (w, h) = match screen.orientation {
        Orientation::Right | Orientation::Left => (h, w),
        _ => (w, h),
    };
    Ok((term, w, h))
}

/// Feeds `screen`'s second part.
#[cfg(feature = "gpu")]
pub(crate) fn feed_next(term: &mut Terminal, next: &[u8]) -> Result<(), String> {
    feed(term, next)
}

/// What the console draws over `screen`'s last frame: a head's overlay or
/// a notice alone.
pub(crate) fn console_overlay(screen: &Screen) -> Result<Option<vtium::term::Overlay>, String> {
    match (screen.overlay, screen.alone) {
        (Some(_), Some(_)) => Err("a head's overlay and a notice alone on one screen".to_owned()),
        (Some(overlay), None) => Ok(Some(overlay.console()?)),
        (None, Some(notice)) => Ok(Some(vtium::term::Overlay::alone(
            notice()?,
            OverlayColors::default(),
        ))),
        (None, None) => Ok(None),
    }
}

fn draw_config<F: Face>(
    screen: &Screen,
    make_font: &impl Fn() -> Font<F>,
    config: Config,
) -> Result<Image, String> {
    let font = make_font();
    let config = screen_config(screen, config);
    let made = picture_cell(screen, font.cell());
    let (mut term, w, h) = prepare(screen, &font)?;
    let mut display = Display::new(w, h);
    let mut r = Renderer::new(font, w, h, config);
    let mut since = Age::NEVER;
    display.frame(&mut r, (&mut term, screen.phase), &mut since);
    if let Some(next) = screen.next {
        later(screen, &mut term, 1, made)?;
        display.frame(&mut r, (&mut term, screen.phase), &mut since);
        feed(&mut term, next)?;
        later(screen, &mut term, 2, made)?;
        display.frame(&mut r, (&mut term, screen.phase), &mut since);
        later(screen, &mut term, 3, made)?;
        display.frame(&mut r, (&mut term, screen.phase), &mut since);
        if display.buffers[0].pixels() != display.buffers[1].pixels() {
            return Err("the two buffers differ after the last frame".to_owned());
        }
        let mut fresh = Display::new(w, h);
        let mut r2 = Renderer::new(make_font(), w, h, config);
        let mut never = Age::NEVER;
        fresh.frame(&mut r2, (&mut term, screen.phase), &mut never);
        if fresh.front().pixels() != display.front().pixels() {
            return Err("the frames drawn in turn differ from a fresh draw".to_owned());
        }
    }
    if let Some(overlay) = console_overlay(screen)? {
        let front = &mut display.buffers[display.back ^ 1];
        let grid = (screen.cols, screen.rows);
        let drawn = overlay.draw(&r, grid, screen.orientation, front);
        if drawn.is_empty() {
            return Err("the overlay drew nothing".to_owned());
        }
    }
    let front = display.front();
    Image::from_xrgb(front.width(), front.height(), front.pixels())
        .ok_or_else(|| format!("a display of {w}x{h} pixels"))
}

